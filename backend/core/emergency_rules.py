"""
응급 차단 규칙 (소유자: 고원영)
안전이 최우선 — '놓치지 않는 것(미탐 최소화)'을 우선한다.
규칙(키워드) 1차 필터 + (확장) LLM 판단을 병행할 수 있다.
"""

EMERGENCY_KEYWORDS = [
    "의식", "의식저하", "의식 저하", "쓰러", "실신", "경련", "발작",
    "숨", "호흡곤란", "숨을 못", "숨이 안",
    "가슴", "흉통", "가슴이 찢", "가슴을 쥐",
    "마비", "한쪽", "말이 어눌", "발음",
    "피를 많이", "대량 출혈", "토혈", "각혈",
    "극심한 통증", "참을 수 없는",
]


def is_emergency(text: str) -> bool:
    """간단 키워드 매칭. 하나라도 걸리면 응급으로 간주(보수적)."""
    if not text:
        return False
    return any(kw in text for kw in EMERGENCY_KEYWORDS)
